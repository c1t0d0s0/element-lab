// 描画用のサイズ計算 (原子半径 pm -> ピクセル半径 8px 〜 26px)
export function getAtomicRenderRadius(atomicRadiusPm: number): number {
  const minPm = 30;
  const maxPm = 350;
  const minRadius = 8;
  const maxRadius = 26;
  const clamped = Math.max(minPm, Math.min(maxPm, atomicRadiusPm));
  const t = (clamped - minPm) / (maxPm - minPm);
  return Math.round(minRadius + t * (maxRadius - minRadius));
}

// 中学・高校の教科書に出てくる炎色反応の元素。これ以外の炎色は暗記用と混ざらないよう「参考」として表示する
export const TEXTBOOK_FLAME_ELEMENTS = ['Li', 'Na', 'K', 'Rb', 'Cs', 'Ca', 'Sr', 'Ba', 'Cu'];

export function isTextbookFlameElement(symbol: string): boolean {
  return TEXTBOOK_FLAME_ELEMENTS.includes(symbol);
}

// 炎色反応情報インターフェース
export interface FlameReactionInfo {
  hasFlameReaction: boolean;
  elementSymbol: string;
  flameColor: string;
  flameColorSecondary: string;
  flameColorNameJa: string;
  flameColorNameEn?: string;
  flameMnemonicJa?: string;
  flameMnemonicEn?: string;
}

// 元素または化合物から炎色反応情報を取得
export function getFlameReactionInfo(kind: string, symbolOrId: string): FlameReactionInfo | null {
  if (kind === 'element') {
    const el = ELEMENTS_DATA[symbolOrId];
    if (el && el.flameColor) {
      return {
        hasFlameReaction: true,
        elementSymbol: el.symbol,
        flameColor: el.flameColor,
        flameColorSecondary: el.flameColorSecondary || el.flameColor,
        flameColorNameJa: el.flameColorNameJa || '炎色反応',
        flameColorNameEn: el.flameColorNameEn,
        flameMnemonicJa: el.flameMnemonicJa,
        flameMnemonicEn: el.flameMnemonicEn
      };
    }
  } else if (kind === 'compound') {
    // 金属塩・金属酸化物などは、構成元素のうち炎色反応を示す元素の色になる (指示薬は対象外)
    const comp = COMPOUNDS_DATA[symbolOrId];
    if (!comp || comp.indicator) return null;
    const flameSymbol = Object.keys(comp.elements).find(sym => ELEMENTS_DATA[sym]?.flameColor);
    if (flameSymbol) return getFlameReactionInfo('element', flameSymbol);
  }
  return null;
}
